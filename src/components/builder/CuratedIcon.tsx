interface CuratedIconProps {
  name?: string;
  size?: number | string;
  strokeWidth?: number;
  color?: string;
  className?: string;
  ariaLabel?: string;
}

export const CuratedIcon: React.FC<CuratedIconProps> = ({
  name = 'Sparkles',
  size = 20,
  strokeWidth = 2,
  color,
  className = '',
  ariaLabel,
}) => {
  const IconComp = ICON_MAP[name] || Sparkles;
  const parsedSize =
    typeof size === 'number'
      ? size
      : parseInt(String(size).replace(/[^0-9.]/g, ''), 10) || 20;

  return (
    <IconComp
      size={parsedSize}
      strokeWidth={strokeWidth}
      style={color ? { color } : undefined}
      className={className}
      aria-label={ariaLabel}
      aria-hidden={ariaLabel ? undefined : true}
    />
  );
};
