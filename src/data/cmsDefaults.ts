function field(
  fieldId: string,
  key: string,
  label: string,
  type: CmsFieldDefinition['type'],
  order: number,
  opts: Partial<CmsFieldDefinition> = {}
): CmsFieldDefinition {
  return {
    fieldId,
    key,
    label,
    type,
    required: false,
    group: 'General',
    order,
    searchable: type === 'short_text' || type === 'long_text' || type === 'rich_text',
    listVisible: order <= 3,
    publiclyExposed: true,
    schemaVersion: 1,
    ...opts,
  };
}

