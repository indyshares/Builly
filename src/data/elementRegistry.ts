export interface ElementConstraints {
  acceptsChildren: boolean;
  allowedChildTypes?: string[];
  allowedParentTypes?: string[];
  maxChildren?: number;
  canBeMoved: boolean;
  canBeReparented: boolean;
  canContainDynamicContent: boolean;
}

