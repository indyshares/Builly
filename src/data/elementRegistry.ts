export const CONTAINER_ELEMENT_TYPES = new Set([
  'container',
  'section',
  'flex-row',
  'stack',
  'grid-2col',
  'grid-container',
  'columns',
  'project-card',
  'repeater',
  'collection-list',
  'collection-grid',
  'custom-carousel',
  'form',
  'modal-box',
]);

export const MAX_NESTING_DEPTH = 16;

export function isContainerElementType(type: string): boolean {
  return CONTAINER_ELEMENT_TYPES.has(type);
}

export function isRepeaterTemplateChild(parentNode: ElementNode | null | undefined): boolean {
  return Boolean(parentNode && parentNode.type === 'repeater');
}

export function getElementConstraints(elementType: string, node?: ElementNode | null): ElementConstraints {
  const def = ELEMENT_REGISTRY.find((el) => el.elementType === elementType);
  const acceptsChildren =
    isContainerElementType(elementType) && node?.componentRef?.mode !== 'linked';
  const maxChildren =
    def?.maxChildren ?? (elementType === 'repeater' ? 1 : undefined);
  return {
    acceptsChildren,
    allowedChildTypes: def?.allowedChildTypes,
    allowedParentTypes: def?.allowedParentTypes,
    maxChildren,
    canBeMoved: def?.canBeMoved !== false,
    canBeReparented: def?.canBeReparented !== false,
    canContainDynamicContent:
      def?.supportsDynamicBinding ||
      elementType === 'repeater' ||
      elementType === 'collection-list' ||
      elementType === 'collection-grid' ||
      isContainerElementType(elementType),
  };
}

export function canNestElement(
  parentNode: ElementNode | null,
  childType: string,
  currentParentDepth = 0
): { allowed: boolean; reason?: string } {
  if (!parentNode) return { allowed: true };
  if (parentNode.locked) {
    return {
      allowed: false,
      reason: `"${parentNode.name}" is locked and cannot accept new children.`,
    };
  }
  if (parentNode.componentRef?.mode === 'linked') {
    return {
      allowed: false,
      reason: `"${parentNode.name}" is a linked component instance. Detach it before changing its inner structure.`,
    };
  }
  if (!isContainerElementType(parentNode.type)) {
    return {
      allowed: false,
      reason: `This element cannot be placed inside "${parentNode.name}" (${parentNode.type}).`,
    };
  }
  if (currentParentDepth >= MAX_NESTING_DEPTH) {
    return {
      allowed: false,
      reason: `Maximum nesting depth (${MAX_NESTING_DEPTH} levels) reached.`,
    };
  }
  const constraints = getElementConstraints(parentNode.type, parentNode);
  if (
    constraints.maxChildren !== undefined &&
    (parentNode.children?.length || 0) >= constraints.maxChildren
  ) {
    return {
      allowed: false,
      reason:
        parentNode.type === 'repeater'
          ? 'Repeater expects 1 item template card. Edit the item template child directly.'
          : `"${parentNode.name}" has reached its maximum of ${constraints.maxChildren} children.`,
    };
  }
  if (
    constraints.allowedChildTypes &&
    constraints.allowedChildTypes.length > 0 &&
    !constraints.allowedChildTypes.includes(childType)
  ) {
    return {
      allowed: false,
      reason: `"${parentNode.name}" only accepts: ${constraints.allowedChildTypes.join(', ')}.`,
    };
  }
  const childDef = ELEMENT_REGISTRY.find((el) => el.elementType === childType);
  if (childDef?.disallowedParentTypes?.includes(parentNode.type)) {
    return {
      allowed: false,
      reason: `"${childDef.name}" cannot be placed directly inside "${parentNode.name}".`,
    };
  }
  if (
    childDef?.allowedParentTypes &&
    childDef.allowedParentTypes.length > 0 &&
    !childDef.allowedParentTypes.includes(parentNode.type)
  ) {
    return {
      allowed: false,
      reason: `"${childDef.name}" can only be placed inside: ${childDef.allowedParentTypes.join(', ')}.`,
    };
  }
  if (parentNode.type === 'form' && childType === 'form') {
    return {
      allowed: false,
      reason: 'Forms cannot be nested inside another Form element.',
    };
  }
  if (parentNode.type === 'repeater' && childType === 'repeater') {
    return {
      allowed: false,
      reason: 'Nested Repeaters are disallowed to prevent unbounded query expansion.',
    };
  }
  if (
    ['navbar', 'header-root', 'footer-root'].includes(childType) &&
    parentNode.type !== 'container' &&
    parentNode.type !== 'section'
  ) {
    return {
      allowed: false,
      reason: `Navigation bar "${childType}" should be placed inside a top-level Section or Header.`,
    };
  }
  if (
    (parentNode.tag === 'header' || parentNode.tag === 'footer') &&
    ['section', 'repeater', 'post-grid', 'post-list'].includes(childType)
  ) {
    return {
      allowed: false,
      reason: `Page-level sections or repeaters cannot be nested inside a ${parentNode.tag} shell.`,
    };
  }
  return { allowed: true };
}

